/** Shapes a user picks as a whole figure (segments excluded). */
export const PICKABLE_FIGURES: FigureShape[] = Object.values(FIGURE_SHAPES).filter((s) => !s.partOf)

export const DEFAULT_FIGURE_SHAPE = 'dancer'

/** Outline scaled to a character's real dimensions (mm), feet at y = 0. */
export function figureOutline(shapeId: string, width: number, height: number): Point2[] {
  const shape = FIGURE_SHAPES[shapeId]
  if (!shape) throw new Error(`unknown figure shape ${shapeId}`)
  return shape.outline.map((p) => ({ x: p.x * width, y: p.y * height }))
}

/** Engraved detail lines scaled to real dimensions (mm). */
export function figureEngraving(shapeId: string, width: number, height: number): Point2[][] {
  return (FIGURE_SHAPES[shapeId]?.engrave ?? []).map((line) =>
    line.map((p) => ({ x: p.x * width, y: p.y * height })),
  )
}

/** Raised detail plates scaled to real dimensions (mm). */
export function figureLayers(shapeId: string, width: number, height: number): Point2[][] {
  return (FIGURE_SHAPES[shapeId]?.layers ?? []).map((plate) =>
    plate.map((p) => ({ x: p.x * width, y: p.y * height })),
  )
}
