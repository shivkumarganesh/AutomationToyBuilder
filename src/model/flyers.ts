import type { Point2 } from './figures'

/**
 * Flyer library: creatures seen from above whose WINGS really move.
 *
 * A flyer is a flat body plate carried level on a fixed post, with a
 * wing each side hinged along the body edge. Each wing is one or two
 * plates hinged in a chain, and every plate rests on the tip of its own
 * pushrod rising from the box — so the wings flap, and with two plates
 * per side and a phase lag between the cams, ripple like a manta.
 *
 * Outlines are normalized:
 *   body: x ∈ [-0.5, 0.5] × body width, y ∈ [0, 1] × body length, nose
 *         at y = 1. The sides are straight (|x| = 0.5) over `straight`,
 *         which is where the wings hinge.
 *   wing: x ∈ [0, 1] × span measured out from the hinge, y ∈ [0, 1] ×
 *         chord. The root edge lies on x = 0. `wingY0` and `chord`
 *         place the wing along the body. The left wing is the mirror.
 */
export interface FlyerShape {
  id: string
  label: string
  body: Point2[]
  wing: Point2[]
  /** Body-length fractions between which the body sides are straight. */
  straight: [number, number]
  /** Body-length fraction where the wing's y = 0 sits. */
  wingY0: number
  /** Wing chord as a fraction of the body length. */
  chord: number
  /** Wing-chord fractions spanned by the root (hinge) edge. */
  root: [number, number]
  defaultBodyWidth: number
  defaultBodyLength: number
  defaultColor: string
}

